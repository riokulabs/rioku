#!/usr/bin/env node
/**
 * ABI surface diff CI check — spec §9.10.1 B4 / Task 1f.117.
 *
 * Approach: marker-hash (chosen over TypeScript AST for stage-1 simplicity).
 *
 * Rationale:
 *   The `/* ABI-SURFACE-START *\/ … /* ABI-SURFACE-END *\/` markers in
 *   `src/hooks/use-host.ts` delimit the exact block that defines the plugin ABI
 *   surface.  We hash this block with SHA-256 and compare against a committed
 *   snapshot at `abi-surface.v1.json`.
 *
 *   When a developer needs to change the surface:
 *     1. Make the change in `use-host.ts`.
 *     2. Bump `CURRENT_ABI_VERSION` in `src/host/abi.ts`.
 *     3. Run `pnpm run abi:update` — updates the hash + records the new version.
 *     4. Commit both files together.
 *
 *   If the surface changes without a version bump, this check exits 1 and CI
 *   fails.
 *
 * Trade-offs vs. TypeScript AST:
 *   + Simpler, no additional deps, extremely fast.
 *   + Catches any change to the declared surface (comments, types, methods).
 *   - Also catches whitespace/comment-only changes (by design — keep docs tidy).
 *   - Does not categorise breaking vs. additive changes automatically.
 *     (A developer must bump the version to signal intent.)
 *
 * A future enhancement can layer in TypeScript AST analysis to distinguish
 * additive additions (new fields) from breaking removals — at that point the
 * hash guard can be relaxed to only fail on breaking changes.
 *
 * Usage:
 *   node scripts/check-abi-surface.mjs          # CI mode — fail on drift
 *   node scripts/check-abi-surface.mjs --update # Update snapshot
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = join(__dirname, '..');
const USE_HOST_PATH = join(WEB_ROOT, 'src', 'hooks', 'use-host.ts');
const ABI_TS_PATH = join(WEB_ROOT, 'src', 'host', 'abi.ts');
const SNAPSHOT_PATH = join(WEB_ROOT, 'abi-surface.v1.json');

const UPDATE_MODE = process.argv.includes('--update');

// ─── Extract ABI surface block ────────────────────────────────────────────────

function extractAbiSurface(fileContent) {
  const start = fileContent.indexOf('/* ABI-SURFACE-START */');
  const end = fileContent.indexOf('/* ABI-SURFACE-END */');

  if (start === -1 || end === -1) {
    console.error(
      'Error: could not find /* ABI-SURFACE-START */ and /* ABI-SURFACE-END */ markers in',
      USE_HOST_PATH,
    );
    process.exit(1);
  }

  // Include both markers in the hash to detect marker removal.
  return fileContent.slice(start, end + '/* ABI-SURFACE-END */'.length);
}

// ─── Extract current ABI version from abi.ts ─────────────────────────────────

function extractAbiVersion(abiContent) {
  const match = /CURRENT_ABI_VERSION\s*:\s*number\s*=\s*(\d+)/.exec(abiContent);
  if (!match || !match[1]) {
    console.error('Error: could not extract CURRENT_ABI_VERSION from', ABI_TS_PATH);
    process.exit(1);
  }
  return parseInt(match[1], 10);
}

// ─── Hash ─────────────────────────────────────────────────────────────────────

function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

// ─── Main ─────────────────────────────────────────────────────────────────────

const useHostContent = readFileSync(USE_HOST_PATH, 'utf8');
const abiContent = readFileSync(ABI_TS_PATH, 'utf8');

const surfaceBlock = extractAbiSurface(useHostContent);
const currentHash = sha256(surfaceBlock);
const currentAbiVersion = extractAbiVersion(abiContent);

if (UPDATE_MODE) {
  // Write a new snapshot — used by `pnpm run abi:update`.
  const snapshot = {
    abiVersion: currentAbiVersion,
    surfaceHash: currentHash,
    updatedAt: new Date().toISOString(),
    note:
      'Generated by scripts/check-abi-surface.mjs --update. ' +
      'Commit this file alongside any ABI surface change + CURRENT_ABI_VERSION bump.',
  };
  writeFileSync(SNAPSHOT_PATH, JSON.stringify(snapshot, null, 2) + '\n');
  console.info(`ABI surface snapshot updated (ABI v${String(currentAbiVersion)}, hash ${currentHash.slice(0, 12)}…)`);
  console.info(`Written to: ${SNAPSHOT_PATH}`);
  process.exit(0);
}

// ─── Check mode ───────────────────────────────────────────────────────────────

if (!existsSync(SNAPSHOT_PATH)) {
  // First run — create the snapshot instead of failing.
  console.warn('ABI surface snapshot not found — creating initial snapshot.');
  const snapshot = {
    abiVersion: currentAbiVersion,
    surfaceHash: currentHash,
    updatedAt: new Date().toISOString(),
    note:
      'Generated by scripts/check-abi-surface.mjs on first run. ' +
      'Commit this file to track future ABI surface changes.',
  };
  writeFileSync(SNAPSHOT_PATH, JSON.stringify(snapshot, null, 2) + '\n');
  console.info(`Snapshot created at: ${SNAPSHOT_PATH}`);
  console.info(`ABI v${String(currentAbiVersion)}, hash ${currentHash.slice(0, 12)}…`);
  process.exit(0);
}

/** @type {{ abiVersion: number; surfaceHash: string; updatedAt: string }} */
const snapshot = JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8'));

const hashMatch = snapshot.surfaceHash === currentHash;
const versionBumped = currentAbiVersion > snapshot.abiVersion;

if (hashMatch) {
  // Surface unchanged — all good.
  console.info(
    `ABI surface check passed (ABI v${String(currentAbiVersion)}, hash ${currentHash.slice(0, 12)}… unchanged).`,
  );
  process.exit(0);
}

// Surface has changed.
if (!versionBumped) {
  console.error('');
  console.error('ABI SURFACE DRIFT DETECTED — CI FAILURE');
  console.error('');
  console.error(
    `The content between /* ABI-SURFACE-START */ and /* ABI-SURFACE-END */ in`,
  );
  console.error(`  ${USE_HOST_PATH}`);
  console.error('has changed, but CURRENT_ABI_VERSION has NOT been bumped.');
  console.error('');
  console.error(`  Snapshot: ABI v${String(snapshot.abiVersion)}, hash ${snapshot.surfaceHash.slice(0, 12)}…`);
  console.error(`  Current:  ABI v${String(currentAbiVersion)}, hash ${currentHash.slice(0, 12)}…`);
  console.error('');
  console.error('To fix:');
  console.error('  1. Bump CURRENT_ABI_VERSION in src/host/abi.ts');
  console.error('  2. Run: pnpm run abi:update');
  console.error('  3. Commit both files together.');
  console.error('');
  process.exit(1);
}

// Surface changed AND version was bumped — update the snapshot automatically
// in CI so it doesn't drift on subsequent commits (developer must have
// committed the new hash via abi:update locally).
console.warn(
  `ABI surface changed: v${String(snapshot.abiVersion)} → v${String(currentAbiVersion)}. ` +
    'Snapshot is stale — run `pnpm run abi:update` locally and commit the result.',
);
console.error('');
console.error('Snapshot hash does not match current surface hash.');
console.error(
  'Even though the ABI version was bumped, the snapshot file must be regenerated.',
);
console.error('Run: pnpm run abi:update   then commit abi-surface.v1.json');
process.exit(1);
